-- ─── 4a. decay_log ──────────────────────────────────────────────────────────

CREATE TABLE decay_log (
    id                      uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    lead_id                 uuid        NOT NULL REFERENCES leads (id) ON DELETE CASCADE,
    run_date                date        NOT NULL,
    days_untouched          integer     NOT NULL,
    decay_applied           integer     NOT NULL,
    previous_decayed_score  integer     NOT NULL,
    new_decayed_score       integer     NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT decay_days_positive CHECK (days_untouched > 0),
    CONSTRAINT decay_applied_non_positive CHECK (decay_applied <= 0),
    CONSTRAINT decay_score_consistent CHECK (new_decayed_score = previous_decayed_score + decay_applied)
);

CREATE INDEX idx_decay_log_lead_id ON decay_log (lead_id);
CREATE INDEX idx_decay_log_run_date ON decay_log (run_date);


-- ─── 4b. rep_activity_log ───────────────────────────────────────────────────

CREATE TABLE rep_activity_log (
    id              uuid            PRIMARY KEY DEFAULT gen_random_uuid(),
    lead_id         uuid            NOT NULL REFERENCES leads (id) ON DELETE CASCADE,
    rep_identifier  text            NOT NULL,
    activity_type   activity_type   NOT NULL,
    notes           text,
    created_at      timestamptz     NOT NULL DEFAULT now()
);

CREATE INDEX idx_rep_activity_lead_id ON rep_activity_log (lead_id);
CREATE INDEX idx_rep_activity_lead_time ON rep_activity_log (lead_id, created_at DESC);


-- ─── 4c. recalibration_reports ──────────────────────────────────────────────

CREATE TABLE recalibration_reports (
    id              uuid                    PRIMARY KEY DEFAULT gen_random_uuid(),
    report_date     date                    NOT NULL,
    quarter         text                    NOT NULL,
    report_data     jsonb                   NOT NULL DEFAULT '{}',
    recommendations jsonb                   NOT NULL DEFAULT '{}',
    status          recalibration_status    NOT NULL DEFAULT 'pending_review',
    reviewed_by     text,
    reviewed_at     timestamptz,
    created_at      timestamptz             NOT NULL DEFAULT now(),

    CONSTRAINT quarter_format CHECK (quarter ~ '^\d{4}-Q[1-4]$')
);

CREATE INDEX idx_recalibration_quarter ON recalibration_reports (quarter);
CREATE INDEX idx_recalibration_status ON recalibration_reports (status);


-- =============================================================================
-- SECTION 5: INDEXES ON LEADS TABLE
