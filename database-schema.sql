    WHERE assigned_rep IS NOT NULL;

CREATE INDEX idx_leads_sla ON leads (sla_deadline)
    WHERE sla_deadline IS NOT NULL AND slack_notified = false;

CREATE INDEX idx_leads_decayed_score ON leads (decayed_score DESC)
    WHERE ingestion_status = 'passed';

CREATE INDEX idx_leads_enrichment ON leads (enrichment_status)
    WHERE enrichment_status IS DISTINCT FROM 'complete';

CREATE INDEX idx_leads_outcome ON leads (outcome, outcome_updated_at)
    WHERE outcome IS NOT NULL;

CREATE INDEX idx_leads_created_at ON leads (created_at DESC);

CREATE INDEX idx_leads_form_data ON leads USING gin (form_data);

CREATE INDEX idx_leads_tech_name ON leads USING gin (technology_name)
    WHERE technology_name IS NOT NULL;


-- =============================================================================
-- SECTION 6: TRIGGERS
-- =============================================================================

CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_leads_updated_at
    BEFORE UPDATE ON leads
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

CREATE OR REPLACE FUNCTION update_lead_rep_activity()
RETURNS trigger AS $$
BEGIN
    UPDATE leads
    SET last_rep_activity_at = NEW.created_at,
        days_untouched = 0
    WHERE id = NEW.lead_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_rep_activity_updates_lead
    AFTER INSERT ON rep_activity_log
    FOR EACH ROW
    EXECUTE FUNCTION update_lead_rep_activity();


