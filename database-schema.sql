-- =============================================================================
-- Lead Intelligence Engine — Complete Supabase PostgreSQL Schema
-- =============================================================================
-- Pipeline: Ingestion → Enrichment → Routing → Scoring → Multipliers → Actioning → Learning
-- Tech: Python · FastAPI · AWS Lambda · Supabase · Cognism · Crunchbase · BuiltWith · Claude API · Slack
-- =============================================================================


-- =============================================================================
-- SECTION 1: ENUM TYPES
-- =============================================================================

CREATE TYPE inquiry_type AS ENUM (
    'contact_sales',
    'rate_limit',
    'baa',
    'zdr',
    'invoicing',
    'support'
);

CREATE TYPE ingestion_status AS ENUM (
    'passed',
    'rejected'
);

CREATE TYPE enrichment_status AS ENUM (
    'complete',
    'partial',
    'minimal'
);

CREATE TYPE geo_region AS ENUM (
    'central',       -- DACH + Eastern Europe
    'uki',           -- UK / Ireland
    'northern',      -- Nordics / Baltics / Benelux
    'southern',      -- Mediterranean / Middle East / North Africa
    'other_emea'     -- Catch-all
);

CREATE TYPE segment AS ENUM (
    'enterprise',    -- >= 2500 employees
    'startup'        -- < 2500 employees
);

CREATE TYPE lead_tier AS ENUM (
    'hot',           -- 130+ → 2-hour SLA
    'warm',          -- 55–129 → 1 business day SLA
    'cold'           -- < 55 → monthly review
);

CREATE TYPE lead_outcome AS ENUM (
    'converted',
    'lost',
    'no_response',
    'in_progress'
);

CREATE TYPE activity_type AS ENUM (
    'call',
    'email',
    'note',
    'meeting',
    'other'
);

CREATE TYPE recalibration_status AS ENUM (
    'pending_review',
    'approved',
    'rejected',
    'partially_applied'
);


-- =============================================================================
-- SECTION 2: CORE TABLE — leads
-- =============================================================================

CREATE TABLE leads (
    -- Primary key
    id                          uuid            PRIMARY KEY DEFAULT gen_random_uuid(),

    -- ─── Form / Ingestion Data ───────────────────────────────────────────
    email                       text            NOT NULL,
    email_domain                text            NOT NULL,
    first_name                  text,
    last_name                   text,
    inquiry_type                inquiry_type    NOT NULL,
    form_data                   jsonb           NOT NULL DEFAULT '{}'::jsonb,
    free_text                   text,
    job_title                   text,

    -- Form-specific fields (nullable — only populated for relevant inquiry types)
    evaluation_journey          text,           -- Contact Sales
    product_interest            text,           -- Contact Sales, BAA
    rate_limit_tier             text,           -- Rate Limit
    tokens_per_minute           text,           -- Rate Limit
    uk_eu_ch_entity             text,           -- BAA
    expected_spend              text,           -- Invoicing

    -- Ingestion gate
    ingestion_status            ingestion_status NOT NULL DEFAULT 'passed',
    rejection_reason            text,

    -- ─── Enrichment Fields (32 fields across 10 categories) ──────────────
    enrichment_status           enrichment_status,

    -- Company basics
    company_name                text,
    company_domain              text,
    company_type                text,
    industry                    text,
    employee_count              integer,
    revenue_estimate            numeric,
    founded_year                integer,

    -- Geography
    hq_country                  text,
    hq_region                   text,
    hq_city                     text,

    -- Event flags
    company_funding_event_flag  boolean         DEFAULT false,
    company_hiring_event_flag   boolean         DEFAULT false,

    -- Growth signals
    operating_status            text,
    funding_status              text,
    number_of_funding_rounds    integer,
    tech_spend_estimate         numeric,

    -- M&A / IPO
    number_of_acquisitions      integer,
    ipo_status                  text,

    -- Funding detail
    last_funding_type           text,
    last_funding_amount         numeric,
    last_funding_date           date,
    total_funding_amount        numeric,
    number_of_investors         integer,

    -- Tech stack (arrays from BuiltWith)
    technology_name             text[],
    technology_tag              text[],
    technology_categories       text[],
    technology_first_detected   date,
    technology_last_detected    date,

    -- Domain reputation (boolean — is company on Global 2000 list)
    is_global_2000              boolean         DEFAULT false,

    -- Competitive intelligence
    competitor_tool_detected    boolean         DEFAULT false,
    competitor_tools_list       text[],

    -- ─── Routing ─────────────────────────────────────────────────────────
    geo_region                  geo_region,
    segment                     segment,
    assigned_rep                text,
    self_reported_employee_count integer,       -- fallback when enrichment unavailable

    -- ─── Scoring: Form-Level Components ──────────────────────────────────
    base_score                          integer DEFAULT 0,
    field_score_evaluation_journey      integer DEFAULT 0,
    field_score_product_interest        integer DEFAULT 0,
    field_score_rate_limit_tier         integer DEFAULT 0,
    field_score_tokens_per_minute       integer DEFAULT 0,
    field_score_uk_eu_ch_entity         integer DEFAULT 0,
    field_score_expected_spend          integer DEFAULT 0,

    -- Claude API scores (with audit inputs stored)
    claude_score_job_title              integer DEFAULT 0,
    claude_score_free_text              integer DEFAULT 0,
    claude_input_job_title              text,   -- exact input sent to Claude for audit
    claude_input_free_text              text,   -- exact input sent to Claude for audit

    total_form_score                    integer DEFAULT 0,

    -- ─── Scoring: Intelligence Multiplier Components (per domain) ────────
    multiplier_firmographic             integer DEFAULT 0,   -- max 18
    multiplier_financial                integer DEFAULT 0,   -- max 15
    multiplier_tech_competitive         integer DEFAULT 0,   -- max 14
    multiplier_organizational           integer DEFAULT 0,   -- max 10
    multiplier_individual               integer DEFAULT 0,   -- max 8
    total_multiplier_score              integer DEFAULT 0,   -- max 65

    -- ─── Final Score & Tier ──────────────────────────────────────────────
    final_score                 integer         DEFAULT 0,   -- max 195
    tier                        lead_tier,
    sla_deadline                timestamptz,
    slack_notified              boolean         NOT NULL DEFAULT false,

    -- ─── Decay / Learning ────────────────────────────────────────────────
    last_rep_activity_at        timestamptz,
    decay_points                integer         NOT NULL DEFAULT 0,
    decayed_score               integer         GENERATED ALWAYS AS (final_score - decay_points) STORED,
    days_untouched              integer,        -- updated by nightly cron

    -- ─── Outcome Tracking (for quarterly recalibration) ──────────────────
    outcome                     lead_outcome,
    outcome_updated_at          timestamptz,

    -- ─── Timestamps ──────────────────────────────────────────────────────
    created_at                  timestamptz     NOT NULL DEFAULT now(),
    updated_at                  timestamptz     NOT NULL DEFAULT now(),

    -- ─── Constraints ─────────────────────────────────────────────────────
    CONSTRAINT email_format CHECK (email ~* '^[^@]+@[^@]+\.[^@]+$'),
    CONSTRAINT decay_points_non_negative CHECK (decay_points >= 0),
    CONSTRAINT rejection_requires_reason CHECK (
        (ingestion_status = 'rejected' AND rejection_reason IS NOT NULL)
        OR ingestion_status = 'passed'
    )
);

COMMENT ON TABLE leads IS 'Core table — one row per inbound lead through the full 7-layer pipeline.';


